import type {
  AnalysisRun,
  Assessment,
  AuditEvent,
  Evidence,
  EvidenceRequest,
  Requirement,
  WorkOrder,
} from '../types.js';

export interface Tables {
  work_orders: WorkOrder;
  requirements: Requirement;
  evidence: Evidence;
  assessments: Assessment;
  analysis_runs: AnalysisRun;
  evidence_requests: EvidenceRequest;
  audit_events: AuditEvent;
}

export type TableName = keyof Tables;

export const TABLE_NAMES: TableName[] = [
  'work_orders',
  'requirements',
  'evidence',
  'assessments',
  'analysis_runs',
  'evidence_requests',
  'audit_events',
];

/**
 * Deliberately small persistence interface. Ids and timestamps are generated by
 * the application, so both implementations (Supabase, local) behave identically.
 */
export interface Db {
  insert<T extends TableName>(table: T, rows: Tables[T] | Tables[T][]): Promise<void>;
  update<T extends TableName>(table: T, id: string, patch: Partial<Tables[T]>): Promise<void>;
  get<T extends TableName>(table: T, id: string): Promise<Tables[T] | null>;
  /** Rows whose columns equal every value in `where`, ordered by `orderBy` ascending. */
  list<T extends TableName>(
    table: T,
    where?: Partial<Tables[T]>,
    orderBy?: keyof Tables[T] & string,
  ): Promise<Tables[T][]>;
}
