-- EvidenceLoop database schema.
-- Run this in the Supabase SQL editor for your project. It is idempotent: running it again
-- upgrades a database created by an earlier version of this file.
--
-- Access model
--   * The backend writes everything using the secret key, which bypasses RLS.
--   * Roles: every signed-in user is a technician unless public.user_roles says otherwise.
--     Only an administrator can assign roles (there are no client write policies), e.g.
--       insert into public.user_roles (id, role) values ('<auth user uuid>', 'reviewer');
--   * Technicians may only READ rows belonging to work orders they own. Reviewers may READ
--     every work order (they review across the organisation). Reads are needed for Supabase
--     Realtime in the browser.
--   * There are no client-side insert/update/delete policies, so the browser cannot alter
--     evidence, decisions, reviews or the audit trail.
--   * Review decisions are additionally enforced by a trigger that applies even to the
--     backend's secret key: only a user with the reviewer role can decide a review, never
--     the person who submitted it, and a decided review cannot be changed.
--   * Ids and timestamps are generated by the backend.

create table if not exists public.work_orders (
  id uuid primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  title text not null,
  description text not null default '',
  location text not null default '',
  template_id text,
  status text not null,
  simulated boolean not null default false,
  archived_at timestamptz,
  created_at timestamptz not null,
  updated_at timestamptz not null
);

create table if not exists public.requirements (
  id uuid primary key,
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  position integer not null,
  title text not null,
  description text not null default '',
  mandatory boolean not null default true,
  evidence_needs jsonb not null default '[]'::jsonb,   -- [{ kind, instruction }]
  status text not null check (status in
    ('PROVEN', 'NOT_PROVEN', 'UNCERTAIN', 'CONTRADICTED', 'ANALYZING')),
  current_assessment_id uuid,
  updated_at timestamptz not null
);

create table if not exists public.evidence (
  id uuid primary key,
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  kind text not null,
  file_name text not null,
  mime_type text not null,
  size_bytes bigint not null,
  sha256 text not null,
  storage_path text not null,
  note text not null default '',
  request_id uuid,
  uploaded_by uuid not null,
  created_at timestamptz not null
);

create table if not exists public.analysis_runs (
  id uuid primary key,
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  trigger text not null check (trigger in ('manual', 'new_evidence')),
  trigger_evidence_id uuid,
  requirement_ids jsonb not null default '[]'::jsonb,
  provider text not null,
  model text,
  simulated boolean not null default false,
  status text not null check (status in ('RUNNING', 'COMPLETED', 'FAILED')),
  error text,
  started_at timestamptz not null,
  completed_at timestamptz
);

-- Append-only: Requirement → Evidence → Observation → Reasoning → Decision.
create table if not exists public.assessments (
  id uuid primary key,
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  requirement_id uuid not null references public.requirements (id) on delete cascade,
  run_id uuid not null references public.analysis_runs (id) on delete cascade,
  status text not null check (status in ('PROVEN', 'NOT_PROVEN', 'UNCERTAIN', 'CONTRADICTED')),
  reasoning text not null,
  confidence double precision check (confidence is null or (confidence >= 0 and confidence <= 1)),
  observations jsonb not null default '[]'::jsonb,     -- [{ evidenceId, kind, text, startSec, endSec }]
  missing_evidence jsonb not null default '[]'::jsonb,
  policy_notes jsonb not null default '[]'::jsonb,
  provider text not null,
  model text,
  simulated boolean not null default false,
  created_at timestamptz not null
);

create table if not exists public.evidence_requests (
  id uuid primary key,
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  run_id uuid references public.analysis_runs (id) on delete cascade, -- null: asked by a reviewer
  requested_by text not null default 'agent',                          -- 'agent' or 'user:<id>'
  requirement_ids jsonb not null default '[]'::jsonb,
  kind text not null,
  instruction text not null,
  status text not null check (status in ('OPEN', 'FULFILLED', 'SUPERSEDED')),
  fulfilled_by_evidence_id uuid,
  created_at timestamptz not null,
  updated_at timestamptz not null
);

-- Append-only audit trail.
create table if not exists public.audit_events (
  id uuid primary key,
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  run_id uuid,
  actor text not null,
  type text not null,
  summary text not null,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null
);

-- Roles. No row = technician.
create table if not exists public.user_roles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('technician', 'reviewer'))
);

-- Human sign-off for contradicted or uncertain work orders.
create table if not exists public.reviews (
  id uuid primary key,
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  status text not null check (status in ('PENDING', 'APPROVED', 'REJECTED', 'EVIDENCE_REQUESTED')),
  status_at_submission text not null,
  submitted_by uuid not null,
  submission_note text not null default '',
  submitted_at timestamptz not null,
  reviewer_id uuid,
  decision_note text,
  decided_at timestamptz,
  check (status = 'PENDING' or (reviewer_id is not null and decided_at is not null
                                and length(coalesce(decision_note, '')) > 0))
);

