-- ---------- Roles ----------

-- security definer so RLS policies can consult user_roles without granting reads on it.
create or replace function public.is_reviewer()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.user_roles r
    where r.id = (select auth.uid()) and r.role = 'reviewer'
  );
$$;

revoke all on function public.is_reviewer() from public;
grant execute on function public.is_reviewer() to authenticated;

-- Applies to every writer, including the backend's secret key.
create or replace function public.enforce_review_roles()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and old.status <> 'PENDING' then
    raise exception 'A decided review cannot be changed';
  end if;
  if tg_op = 'INSERT' and exists (
    select 1 from public.user_roles r where r.id = new.submitted_by and r.role = 'reviewer'
  ) then
    raise exception 'Reviewers cannot submit work orders for review';
  end if;
  if new.status <> 'PENDING' then
    if new.reviewer_id is null or not exists (
      select 1 from public.user_roles r where r.id = new.reviewer_id and r.role = 'reviewer'
    ) then
      raise exception 'Only a user with the reviewer role can decide a review';
    end if;
    if new.reviewer_id = new.submitted_by then
      raise exception 'A review cannot be decided by the person who submitted it';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists reviews_enforce_roles on public.reviews;
create trigger reviews_enforce_roles
  before insert or update on public.reviews
  for each row execute function public.enforce_review_roles();

-- ---------- Row Level Security ----------

alter table public.work_orders enable row level security;
alter table public.requirements enable row level security;
alter table public.evidence enable row level security;
alter table public.analysis_runs enable row level security;
alter table public.assessments enable row level security;
alter table public.evidence_requests enable row level security;
alter table public.audit_events enable row level security;
alter table public.reviews enable row level security;
alter table public.user_roles enable row level security;

drop policy if exists "Owners can read their work orders" on public.work_orders;
create policy "Owners can read their work orders" on public.work_orders
  for select to authenticated
  using (owner_id = (select auth.uid()));

drop policy if exists "Reviewers can read all work orders" on public.work_orders;
create policy "Reviewers can read all work orders" on public.work_orders
  for select to authenticated
  using ((select public.is_reviewer()));

drop policy if exists "Users can read their own role" on public.user_roles;
create policy "Users can read their own role" on public.user_roles
  for select to authenticated
  using (id = (select auth.uid()));

do $$
declare
  child text;
begin
  foreach child in array array[
    'requirements', 'evidence', 'analysis_runs', 'assessments', 'evidence_requests', 'audit_events',
    'reviews'
  ] loop
    execute format('drop policy if exists "Owners can read" on public.%I', child);
    execute format(
      'create policy "Owners can read" on public.%I for select to authenticated using (
         exists (
           select 1 from public.work_orders w
           where w.id = %I.work_order_id and w.owner_id = (select auth.uid())
         )
       )', child, child);
    execute format('drop policy if exists "Reviewers can read" on public.%I', child);
    execute format(
      'create policy "Reviewers can read" on public.%I for select to authenticated
         using ((select public.is_reviewer()))', child);
  end loop;
end $$;

-- ---------- Privileges ----------
-- Stated explicitly rather than relying on project defaults, which differ between
-- Supabase projects. RLS above still decides which rows `authenticated` can see.

do $$
declare
  t text;
begin
  foreach t in array array[
    'work_orders', 'requirements', 'evidence', 'analysis_runs', 'assessments',
    'evidence_requests', 'audit_events', 'reviews', 'user_roles'
  ] loop
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
    execute format('grant all on public.%I to service_role', t);
  end loop;
end $$;

-- ---------- Realtime ----------
-- The dashboard subscribes to these tables to update live as the agent works.

do $$
declare
  t text;
begin
  foreach t in array array['work_orders', 'requirements', 'evidence_requests', 'audit_events', 'reviews'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;

-- ---------- Health check ----------
-- Read by `npm run check:supabase` with the secret key only. Reports catalog state the
-- REST API cannot show: RLS per table, policy counts, Realtime tables, the review trigger.

create or replace function public.evidenceloop_schema_report()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'rls', (
      select coalesce(jsonb_object_agg(c.relname, c.relrowsecurity), '{}'::jsonb)
      from pg_catalog.pg_class c
      join pg_catalog.pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relkind = 'r'
    ),
    'policies', (
      select coalesce(jsonb_object_agg(p.tablename, p.total), '{}'::jsonb)
      from (
        select tablename, count(*) as total from pg_catalog.pg_policies
        where schemaname = 'public' group by tablename
      ) p
    ),
    'realtime', (
      select coalesce(jsonb_agg(t.tablename), '[]'::jsonb)
      from pg_catalog.pg_publication_tables t
      where t.pubname = 'supabase_realtime' and t.schemaname = 'public'
    ),
    'reviewTrigger', exists (
      select 1 from pg_catalog.pg_trigger
      where tgname = 'reviews_enforce_roles' and not tgisinternal
    )
  );
$$;

revoke all on function public.evidenceloop_schema_report() from public, anon, authenticated;
grant execute on function public.evidenceloop_schema_report() to service_role;

